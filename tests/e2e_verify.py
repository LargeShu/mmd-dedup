#!/usr/bin/env python3
"""
Вторая половина сквозной проверки: сверка диска с ожиданиями.

tests/e2e_decisions.js нажал кнопки в отчёте и записал два файла:
решения (то, что уходит в 04_apply) и ожидания (что человек видел
на экране). После прогона 04_apply --move этот скрипт проверяет, что
диск изменился ровно так, как обещал интерфейс.

    python3 tests/e2e_verify.py expect.json decisions.json

Проверяется три вещи, и все три — про ШОВ между отчётом и исполнителем:

  1. исчезли ровно те файлы, что были подписаны «УДАЛИТЬ» на экране;
  2. остались все, что подписаны «ОСТАВИТЬ» и «оставить обе»;
  3. подсказка у флажка называла тот же файл, что реально исчез.

Именно этот шов дважды давал дефекты: каждая сторона по отдельности
была «зелёной», а вместе они расходились.
"""

import json
import os
import sys


def main():
    if len(sys.argv) != 3:
        raise SystemExit("нужно: expect.json decisions.json")
    with open(sys.argv[1], encoding="utf-8") as fh:
        ожидания = json.load(fh)
    with open(sys.argv[2], encoding="utf-8") as fh:
        решения = json.load(fh)

    беды = []

    for p in ожидания["исчезнут"]:
        if os.path.exists(p):
            беды.append(f"остался на месте, хотя подписан «УДАЛИТЬ»: {p}")
    for p in ожидания["останутся"]:
        if not os.path.exists(p):
            беды.append(f"ИСЧЕЗ, хотя должен был остаться: {p}")

    # Экран и исполнитель обязаны называть один файл.
    к_удалению = {r["путь"] for r in решения.get("к_удалению", [])}
    for з in ожидания["подписи"]:
        экран = з["удалить_на_экране"]
        if экран not in к_удалению:
            беды.append(
                "расхождение экрана и решения: на карточке «УДАЛИТЬ» "
                f"стоит {экран}, а в JSON его нет")
        if os.path.basename(экран) not in з["подсказка"]:
            беды.append(
                f"подсказка называет не тот файл: «{з['подсказка']}», "
                f"а удаляется {os.path.basename(экран)}")

    # «Оставить обе» не имеет права попасть в удаление ни при каких условиях.
    обе = {r["путь"] for r in решения.get("оставлены_обе", [])}
    for p in обе & к_удалению:
        беды.append(f"файл помечен «оставить обе» и при этом удаляется: {p}")

    if беды:
        print("  СКВОЗНАЯ ПРОВЕРКА ПРОВАЛЕНА:")
        for b in беды:
            print(f"    {b}")
        return 1

    print(f"  исчезли ровно подписанные ({len(ожидания['исчезнут'])}), "
          f"остальные на месте ({len(ожидания['останутся'])})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
